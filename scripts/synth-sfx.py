#!/usr/bin/env python3
"""Synthesise the Magician Clipper's built-in SFX (Batch 9).

Only sounds shipped in this repo are ever offered as SFX — these two
files, generated by this script with the Python standard library only
(no recorded samples, no downloads, nothing from a competitor):

- whoosh.wav (0.8s): white noise through a one-pole lowpass whose
  cutoff sweeps 300 -> 4500 Hz, with a fast attack and smooth decay —
  the airy sweep played at the clip start and at each auto-zoom
  punch-in.
- pop.wav (0.15s): a sine burst sweeping 900 -> 350 Hz with an
  exponential decay — the short click played on each keyword pop-up.

Regenerate with:  python3 scripts/synth-sfx.py
Outputs land in services/video-engine/assets/sfx/ next to the README.
"""
import math
import random
import struct
import wave
from pathlib import Path

SR = 48000
OUT_DIR = Path(__file__).resolve().parent.parent / "services" / "video-engine" / "assets" / "sfx"


def _write_wav(path: Path, samples: list[float]) -> None:
    peak = max((abs(s) for s in samples), default=0.0) or 1.0
    frames = b"".join(
        struct.pack("<h", int(max(-1.0, min(1.0, s / peak * 0.9)) * 32767))
        for s in samples
    )
    with wave.open(str(path), "wb") as fh:
        fh.setnchannels(1)
        fh.setsampwidth(2)
        fh.setframerate(SR)
        fh.writeframes(frames)


def make_whoosh(duration: float = 0.8) -> list[float]:
    n = int(SR * duration)
    out: list[float] = []
    y = 0.0
    rng = random.Random(20261125)  # fixed seed: reproducible file
    for i in range(n):
        t = i / SR
        # Cutoff sweeps 300 -> 4500 Hz (exponential).
        fc = 300.0 * (4500.0 / 300.0) ** (t / duration)
        a = 1.0 - math.exp(-2.0 * math.pi * fc / SR)
        x = rng.uniform(-1.0, 1.0)
        y += a * (x - y)
        # Fast attack (50ms), smooth squared decay.
        env = min(1.0, t / 0.05) * (1.0 - t / duration) ** 2
        out.append(y * env * 2.5)
    return out


def make_pop(duration: float = 0.15) -> list[float]:
    n = int(SR * duration)
    out: list[float] = []
    phase = 0.0
    for i in range(n):
        t = i / SR
        # Pitch drops 900 -> 350 Hz across the burst.
        f = 900.0 * (350.0 / 900.0) ** (t / duration)
        phase += 2.0 * math.pi * f / SR
        env = math.exp(-t / 0.03)
        out.append(math.sin(phase) * env)
    return out


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    _write_wav(OUT_DIR / "whoosh.wav", make_whoosh())
    _write_wav(OUT_DIR / "pop.wav", make_pop())
    for name in ("whoosh.wav", "pop.wav"):
        p = OUT_DIR / name
        print(f"{p}  {p.stat().st_size} bytes")


if __name__ == "__main__":
    main()
